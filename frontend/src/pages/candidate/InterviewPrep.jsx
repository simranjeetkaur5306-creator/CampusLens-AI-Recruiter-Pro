import { useState } from "react";
import { useSearchParams } from "react-router-dom";
import { MessageSquare } from "lucide-react";
import JobSelect from "../../components/ui/JobSelect";
import PageHeader from "../../components/ui/PageHeader";
import { EmptyState, ErrorState, InlineError, Spinner } from "../../components/ui/States";
import { useToast } from "../../context/ToastContext";
import { useAsync } from "../../hooks/useAsync";
import { errorMessage } from "../../services/api";
import { getJobOptions } from "../../services/candidateApi";
import { CATEGORIES, generateQuestions, getQuestionHistory } from "../../services/interviewApi";
import { formatDate } from "../../utils/format";

export default function InterviewPrep() {
  const toast = useToast();
  const [params, setParams] = useSearchParams();
  const jobId = params.get("job") || "";
  const [count, setCount] = useState(5);
  const [result, setResult] = useState(null);
  const [tab, setTab] = useState(CATEGORIES[0][0]);
  const [generating, setGenerating] = useState(false);
  const [refreshKey, setRefreshKey] = useState(0);

  const options = useAsync(getJobOptions, []);
  const history = useAsync(
    () => (jobId ? getQuestionHistory(jobId) : Promise.resolve([])),
    [jobId, refreshKey]
  );

  if (options.loading) return <Spinner label="Loading jobs…" />;
  if (options.error) return <ErrorState message={options.error} onRetry={options.reload} />;

  const onJobChange = (v) => {
    setResult(null);
    setParams(v ? { job: v } : {});
  };

  const onGenerate = async () => {
    setGenerating(true);
    try {
      const set = await generateQuestions(jobId, count);
      setResult(set);
      setTab(CATEGORIES[0][0]);
      setRefreshKey((k) => k + 1);
      const total = Object.values(set.questions).reduce((n, list) => n + list.length, 0);
      if (total === 0) toast.error("No questions were returned for this job.");
      else toast.success(set.source === "fallback" ? "Template questions ready." : "Interview questions generated.");
    } catch (err) {
      toast.error(errorMessage(err));
    } finally {
      setGenerating(false);
    }
  };

  const questions = result?.questions?.[tab] ?? [];

  return (
    <>
      <PageHeader title="AI Interview Preparation" subtitle="Questions based on the job and your resume's extracted skills." />

      <div className="grid gap-4 rounded-2xl border border-slate-200 bg-white p-5 sm:grid-cols-[1fr_auto_auto] sm:items-end">
        <JobSelect options={options.data ?? []} value={jobId} onChange={onJobChange} />
        <div>
          <label htmlFor="count" className="mb-1 block text-sm font-medium text-slate-700">Per category</label>
          <select id="count" value={count} onChange={(e) => setCount(Number(e.target.value))} className="rounded-lg border border-slate-300 bg-white px-3 py-2.5 text-sm">
            {[3, 5, 8].map((n) => <option key={n} value={n}>{n} questions</option>)}
          </select>
        </div>
        <button
          onClick={onGenerate}
          disabled={!jobId || generating}
          className="rounded-lg bg-navy-900 px-5 py-2.5 text-sm font-semibold text-white hover:bg-navy-800 disabled:opacity-50"
        >
          {generating ? "Generating…" : "Generate questions"}
        </button>
      </div>

      {generating && <Spinner label="Generating questions…" />}

      {!generating && !result && (
        <div className="mt-6">
          <EmptyState
            icon={MessageSquare}
            title={jobId ? "Ready when you are" : "Choose a job"}
            text={jobId ? "Press Generate to get technical, conceptual, project and HR questions." : "Select a job to prepare for."}
          />
        </div>
      )}

      {!generating && result && (
        <section className="mt-6 rounded-2xl border border-slate-200 bg-white p-5">
          {result.source === "fallback" ? (
            <p className="mb-4 rounded-lg border border-amber-200 bg-amber-50 p-3 text-sm text-amber-800">
              {result.notice || "AI service unavailable. Showing template questions."}
            </p>
          ) : result.source === "llm" ? (
            <p className="mb-4 text-xs text-slate-500">
              Generated by AI{result.model ? ` (${result.model})` : ""}. Review answers critically.
            </p>
          ) : null}

          <div className="flex flex-wrap gap-2">
            {CATEGORIES.map(([key, label]) => (
              <button
                key={key}
                onClick={() => setTab(key)}
                className={`rounded-lg px-3 py-1.5 text-sm font-medium transition ${
                  tab === key ? "bg-navy-900 text-white" : "bg-slate-100 text-slate-600 hover:bg-slate-200"
                }`}
              >
                {label} ({result.questions?.[key]?.length ?? 0})
              </button>
            ))}
          </div>

          {questions.length === 0 ? (
            <p className="mt-5 text-sm text-slate-500">No questions in this category.</p>
          ) : (
            <ol className="mt-5 space-y-3">
              {questions.map((q, i) => (
                <li key={i} className="rounded-xl border border-slate-200 p-4 text-sm">
                  <p className="text-slate-800"><span className="mr-2 font-bold text-brand-600">{i + 1}.</span>{q.question}</p>
                  {q.tests && <p className="mt-1 text-xs text-slate-500">Assesses: {q.tests}</p>}
                </li>
              ))}
            </ol>
          )}
        </section>
      )}

      {jobId && (
        <section className="mt-8">
          <h2 className="mb-3 font-semibold text-navy-900">Previous sets for this job</h2>
          {history.loading ? (
            <Spinner label="Loading history…" />
          ) : history.error ? (
            <InlineError what="history" message={history.error} />
          ) : history.data.length === 0 ? (
            <p className="text-sm text-slate-500">Nothing generated for this job yet.</p>
          ) : (
            <ul className="space-y-2">
              {history.data.map((h) => (
                <li key={h.id ?? h.createdAt}>
                  <button
                    onClick={() => { setResult(h); setTab(CATEGORIES[0][0]); }}
                    className="flex w-full items-center justify-between rounded-xl border border-slate-200 bg-white px-4 py-3 text-left text-sm hover:bg-slate-50"
                  >
                    <span>{formatDate(h.createdAt)}</span>
                    <span className="text-xs text-slate-500">
                      {h.source === "fallback" ? "Template" : h.source === "llm" ? "AI generated" : ""}
                    </span>
                  </button>
                </li>
              ))}
            </ul>
          )}
        </section>
      )}
    </>
  );
}